"""Pydantic data models for Why Did AI Do That? (WDAIDT) V0.6.

Single source of truth for the API agreement between Extension and Backend.
Defines the Adaptive Analysis Architecture & Dynamic Document Schema.
"""

from typing import Annotated, List, Literal, Optional, Union
from pydantic import BaseModel, ConfigDict, Field, model_validator

MAX_PROMPT_CHARS = 8000
MAX_RESPONSE_CHARS = 20000
MAX_TITLE_CHARS = 200
MAX_BLOCKS = 50


class BaseBlock(BaseModel):
    """Base model for all document content blocks."""
    model_config = ConfigDict(extra="ignore")


class HeadingBlock(BaseBlock):
    """Heading content block (levels 1-6)."""
    type: Literal["heading"] = "heading"
    level: int = Field(default=2, ge=1, le=6, description="Heading level (1 to 6).")
    content: str = Field(..., min_length=1, max_length=1000, description="Heading text.")


class ParagraphBlock(BaseBlock):
    """Paragraph explanatory text block."""
    type: Literal["paragraph"] = "paragraph"
    content: str = Field(..., min_length=1, max_length=5000, description="Paragraph text.")


class ListBlock(BaseBlock):
    """Ordered or unordered list block."""
    type: Literal["list"] = "list"
    style: Literal["ordered", "unordered"] = Field(
        default="unordered",
        description="List style: 'ordered' or 'unordered'.",
    )
    items: List[str] = Field(
        default_factory=list,
        max_length=50,
        description="List items.",
    )


class CodeBlock(BaseBlock):
    """Monospace code snippet block."""
    type: Literal["code"] = "code"
    language: Optional[str] = Field(
        default=None,
        max_length=50,
        description="Programming language identifier (e.g. 'python', 'javascript').",
    )
    content: str = Field(..., min_length=1, max_length=10000, description="Code content.")


class QuoteBlock(BaseBlock):
    """Quoted or referenced text block."""
    type: Literal["quote"] = "quote"
    content: str = Field(..., min_length=1, max_length=3000, description="Quote text.")


class TableBlock(BaseBlock):
    """Structured tabular data block."""
    type: Literal["table"] = "table"
    headers: List[str] = Field(
        default_factory=list,
        max_length=20,
        description="Column header titles.",
    )
    rows: List[List[str]] = Field(
        default_factory=list,
        max_length=50,
        description="Table rows containing cell values.",
    )


class CalloutBlock(BaseBlock):
    """Visual callout note block for info, warnings, tips, etc."""
    type: Literal["callout"] = "callout"
    variant: Literal["info", "warning", "caution", "tip", "note", "important"] = Field(
        default="info",
        description="Callout semantic visual variant.",
    )
    title: Optional[str] = Field(
        default=None,
        max_length=150,
        description="Optional callout header title.",
    )
    content: str = Field(..., min_length=1, max_length=3000, description="Callout body text.")


class DividerBlock(BaseBlock):
    """Horizontal section divider line."""
    type: Literal["divider"] = "divider"


class NextPromptBlock(BaseBlock):
    """Suggested follow-up prompt block with a one-click copy affordance."""
    type: Literal["next_prompt"] = "next_prompt"
    prompt: Optional[str] = Field(
        default=None,
        max_length=5000,
        description="Ready-to-use follow-up prompt text.",
    )
    content: Optional[str] = Field(
        default=None,
        max_length=5000,
        description="Alternative field holding the ready-to-use follow-up prompt.",
    )
    title: Optional[str] = Field(
        default="Suggested Next Prompt",
        max_length=150,
        description="Label or context describing the purpose of the suggested prompt.",
    )

    @model_validator(mode="after")
    def sync_prompt_and_content(self):
        text = self.prompt or self.content
        if not text or not text.strip():
            raise ValueError("next_prompt block must contain non-empty prompt or content")
        clean_text = text.strip()
        if not self.prompt:
            self.prompt = clean_text
        if not self.content:
            self.content = clean_text
        return self


# Discriminated union of all supported content blocks
ContentBlock = Annotated[
    Union[
        HeadingBlock,
        ParagraphBlock,
        ListBlock,
        CodeBlock,
        QuoteBlock,
        TableBlock,
        CalloutBlock,
        DividerBlock,
        NextPromptBlock,
    ],
    Field(discriminator="type"),
]


class AnalysisDocument(BaseModel):
    """Validated structured analysis document generated by Gemini."""
    model_config = ConfigDict(extra="ignore")

    title: str = Field(
        ...,
        min_length=1,
        max_length=MAX_TITLE_CHARS,
        description="High-level descriptive title of the analysis.",
    )
    blocks: List[ContentBlock] = Field(
        ...,
        min_length=1,
        max_length=MAX_BLOCKS,
        description="Ordered collection of validated content blocks.",
    )


class AnalysisRequest(BaseModel):
    """Incoming request to POST /analyze."""
    model_config = ConfigDict(extra="ignore")

    prompt: str = Field(
        ...,
        description="The latest user message.",
    )
    response: str = Field(
        ...,
        description="The latest ChatGPT assistant reply.",
    )
    request_id: Optional[str] = Field(
        default=None,
        description="Optional client-generated ID echoed back to ignore stale results.",
    )
    response_style: Optional[str] = Field(
        default=None,
        description="User-selected response style preset (e.g. 'Professional and direct', 'Casual and natural').",
    )
    custom_instructions: Optional[str] = Field(
        default=None,
        max_length=1000,
        description="Optional custom style instructions provided by the user.",
    )
    analysis_depth: Optional[str] = Field(
        default=None,
        description="Analysis depth preference ('Brief', 'Balanced', 'Detailed').",
    )


class AnalysisResult(BaseModel):
    """Structured response returned by POST /analyze in V0.6."""
    model_config = ConfigDict(extra="ignore")

    request_id: Optional[str] = Field(
        default=None,
        description="Echoed client request_id if provided.",
    )
    analysis: AnalysisDocument = Field(
        ...,
        description="Validated structured document containing title and content blocks.",
    )


class ErrorDetail(BaseModel):
    """Inner error payload."""
    code: str = Field(..., description="Machine-readable error code.")
    message: str = Field(..., description="Human-readable safe error message.")


class ErrorResponse(BaseModel):
    """Standardized error envelope per API agreement."""
    error: ErrorDetail


class HealthResponse(BaseModel):
    """GET /health response."""
    status: str = "ok"
